(async () => {
  const p = global.__rl16, { assert, tick, root, click, input, button, config, waitConfig, requests } = p;
  const findings = {};
  const before = JSON.stringify(config()), baseline = requests.length;
  await click('Profiles');
  assert(button('Edit').disabled && button('Delete').disabled, 'Built-in must be read-only');
  await click('Duplicate');
  await input('Profile name', 'Default');
  assert(button('Save profile').disabled && root().innerText.includes('reserved'), 'Reserved name validation');
  await input('Profile name', 'Ticket 16 nested');
  await input('Message paths', 'event/text');
  assert(button('Save profile').disabled && root().innerText.includes('Invalid field path'), 'Malformed path validation');
  assert(JSON.stringify(config()) === before, 'Invalid draft wrote settings');
  await input('Message paths', '/event/text\n/message');
  await input('Application timestamp paths', '/event/time');
  await input('Level paths', '/event/severity');
  await input('Inline fields', '/event\n/a~1b\n/a~0b\n/items/0/code');
  await input('Hidden fields', '/event/internal');
  await input('Numeric timestamps', 'seconds');
  await click('Add mapping');
  assert(button('Save profile').disabled, 'Blank map source should block Save');
  await input('Mapping 1 source type', 'number');
  await input('Mapping 1 source', '30');
  await input('Mapping 1 target', 'INFO');
  await click('Add mapping');
  await input('Mapping 2 source', '30');
  await input('Mapping 2 target', 'WARN');
  await input('Sample logs', '{"event":{"text":"Preview α🙂\\nmessage","time":1000,"severity":30,"code":"E1","internal":"hidden"}}');
  const preview = root().querySelector('[aria-label="Profile preview"]').innerText;
  assert(preview.includes('Preview α🙂\nmessage') && preview.includes('INFO') && preview.includes('E1') && !preview.includes('hidden'), 'Incorrect draft preview');
  assert(JSON.stringify(config()) === before, 'Preview persisted draft/sample');
  findings.preview = preview;
  await click('Save profile');
  await waitConfig(c => c.profiles?.length === 1);
  const first = config().profiles[0]; p.firstId = first.id;
  assert(first.name === 'Ticket 16 nested', 'First save missing');
  assert(!JSON.stringify(config()).includes('Preview'), 'Sample was persisted');
  await input('Global default', first.id);
  await waitConfig(c => c.globalDefault === first.id);
  await click('Close profiles');
  assert(root().querySelector('.rl-row .rl-message').textContent === 'Nested α🙂\nmessage', 'Save/global default did not reformat retained rows');
  assert(root().querySelector('.rl-row .rl-level').textContent === 'INFO', 'Numeric map not applied');
  const inline = [...root().querySelectorAll('.rl-row')][0].innerText;
  assert(inline.includes('E1') && inline.includes('slash') && inline.includes('tilde') && inline.includes('first') && !inline.includes('private'), 'Inline/hidden/extracted fields failed');
  await input('Find in logs', 'α🙂');
  assert(root().querySelector('.rl-find-count').textContent.includes('1 of 1'), 'Find did not search reformatted decoded message');
  await input('Profile', 'default');
  assert(root().querySelector('.rl-row .rl-message').textContent === 'Default message', 'Manual built-in selection failed');
  assert(root().querySelector('.rl-find-count').textContent.includes('1 of 1'), 'Find must still include Unicode present in original application text');
  await input('Profile', first.id);
  await click('Profiles');
  await input('Saved profile', first.id);
  await click('Edit');
  await input('Profile name', 'Discarded');
  await input('Message paths', '/items/0/code');
  await click('Cancel');
  assert(config().profiles[0].name === first.name && config().profiles[0].format.messagePaths[0] === '/event/text', 'Cancel changed saved rules');
  await click('Duplicate');
  await input('Profile name', 'Ticket 16 alternate');
  await input('Message paths', '/items/0/code');
  await input('Numeric timestamps', 'milliseconds');
  await click('Save profile');
  await waitConfig(c => c.profiles.length === 2);
  const second = config().profiles[1]; p.secondId = second.id;
  assert(config().profiles[0].format.messagePaths[0] === '/event/text', 'Editing duplicate changed source');
  await input('Saved profile', first.id);
  await click('Edit');
  await input('Profile name', 'ticket 16 alternate');
  assert(button('Save profile').disabled && root().innerText.includes('unique'), 'Duplicate-name validation missing');
  await input('Profile name', 'Ticket 16 renamed');
  await click('Save profile');
  await waitConfig(c => c.profiles[0].name === 'Ticket 16 renamed');
  assert(config().globalDefault === first.id && config().profiles[0].id === first.id && config().profiles[1].id === second.id, 'Rename changed reference/order');
  await click('Close profiles');
  assert(root().querySelector('[aria-label="Profile"]').value === first.id, 'Rename changed manual choice');
  await input('Profile', second.id);
  assert(root().querySelector('.rl-row .rl-message').textContent === 'first', 'Independent duplicate not selectable');
  await click('Profiles'); await input('Saved profile', second.id); await click('Delete'); await click('Keep profile');
  assert(config().profiles.length === 2, 'Canceled delete changed profiles');
  await click('Delete'); await click('Confirm delete');
  await waitConfig(c => c.profiles.length === 1);
  await click('Close profiles');
  assert(root().querySelector('[aria-label="Profile"]').value === '', 'Deleting manual choice did not return to Auto');
  assert(root().querySelector('.rl-row .rl-message').textContent === 'Nested α🙂\nmessage', 'Auto did not use global default');
  // Create another independent complete profile for full-configuration restart evidence.
  await click('Profiles'); await input('Saved profile', first.id); await click('Duplicate');
  await input('Profile name', 'Ticket 16 alternate'); await input('Message paths', '/items/0/code');
  await input('Numeric timestamps', 'milliseconds'); await click('Save profile');
  await waitConfig(c => c.profiles.length === 2); p.secondId = config().profiles[1].id;
  await click('Close profiles');
  assert(requests.length === baseline, 'Editor/formatting triggered a log request');
  findings.inline = inline; findings.savedConfiguration = config(); findings.requestsDuringEditing = requests.slice(baseline);
  findings.manualDeletedToAuto = root().querySelector('[aria-label="Profile"]').value;
  findings.paused = !!button('Resume');
  return findings;
})()
